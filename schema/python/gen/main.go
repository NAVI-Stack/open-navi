// Command gen emits stdlib-only Python models for NAVI's governed types,
// sourced from the canonical Go definitions in internal/schema, internal/governor,
// and internal/connectors.
//
// It is the Go-sourcing step of the single Python codegen flow: schema/python/
// generate.py invokes it before running datamodel-codegen, so `make generate-python`
// produces both the Pydantic models (from JSON Schema) and the governed contracts
// (from Go). It is not a parallel generator — datamodel-codegen cannot source Go
// types, and the Language-Layer Contract (§7) requires governed DTOs to be
// generated from internal/schema, not hand-written.
//
// The shared input set and type discovery live in schema/codegen, which the
// TypeScript emitter (schema/ts/gen) renders from too — so both languages emit the
// same governed contracts from the same Go types. This command only renders the
// Python (stdlib dataclasses + enum) projection of that one Model.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strconv"
	"strings"

	"github.com/ceoai/navi/schema/codegen"
)

// pythonKeywords are reserved words that may not be used as dataclass field names.
var pythonKeywords = map[string]bool{
	"False": true, "None": true, "True": true, "and": true, "as": true,
	"assert": true, "async": true, "await": true, "break": true, "class": true,
	"continue": true, "def": true, "del": true, "elif": true, "else": true,
	"except": true, "finally": true, "for": true, "from": true, "global": true,
	"if": true, "import": true, "in": true, "is": true, "lambda": true,
	"nonlocal": true, "not": true, "or": true, "pass": true, "raise": true,
	"return": true, "try": true, "while": true, "with": true, "yield": true,
}

func main() {
	root := flag.String("root", ".", "module root directory")
	out := flag.String("out", filepath.Join("schema", "python", "navi_schema", "governed.py"), "output .py path")
	flag.Parse()

	model, err := codegen.Build(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}

	src, err := emit(model)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}

	outPath := *out
	if !filepath.IsAbs(outPath) {
		outPath = filepath.Join(*root, outPath)
	}
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(outPath, []byte(src), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	fmt.Println("gen: wrote", outPath)
}

// pyType maps a Go type to a Python annotation + dataclass default, resolving enum
// references through the model. It is a pure projection — discovery already
// happened in codegen.Build.
func pyType(m *codegen.Model, t reflect.Type) (annotation, defaultExpr string) {
	if t.Kind() == reflect.Pointer {
		inner, _ := pyType(m, t.Elem())
		return "Optional[" + inner + "]", "= None"
	}
	if e, ok := m.Enum(t); ok {
		if e.IsString {
			return e.Name, `= ""`
		}
		return e.Name, "= 0"
	}
	switch t.Kind() {
	case reflect.String:
		return "str", `= ""`
	case reflect.Bool:
		return "bool", "= False"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return "int", "= 0"
	case reflect.Float32, reflect.Float64:
		return "float", "= 0.0"
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 { // []byte / json.RawMessage
			return "Any", "= None"
		}
		inner, _ := pyType(m, t.Elem())
		return "List[" + inner + "]", "= field(default_factory=list)"
	case reflect.Map:
		k, _ := pyType(m, t.Key())
		v, _ := pyType(m, t.Elem())
		return "Dict[" + k + ", " + v + "]", "= field(default_factory=dict)"
	case reflect.Struct:
		if t.PkgPath() == "time" && t.Name() == "Time" {
			return "str", `= ""` // RFC3339 timestamp
		}
		if codegen.IsKernelPkg(t.PkgPath()) && t.Name() != "" {
			return t.Name(), "= field(default_factory=" + t.Name() + ")"
		}
		return "Any", "= None"
	case reflect.Interface:
		return "Any", "= None"
	default:
		return "Any", "= None"
	}
}

// emit renders the full Python module from the contract model.
func emit(m *codegen.Model) (string, error) {
	seen := map[string]bool{}
	for _, e := range m.Enums {
		seen[e.Name] = true
	}
	for _, s := range m.Structs {
		seen[s.Name] = true
		for _, f := range s.Fields {
			if pythonKeywords[f.JSONName] {
				return "", fmt.Errorf("field %q in %s is a python keyword", f.JSONName, s.Name)
			}
		}
	}

	names := make([]string, 0, len(seen))
	for n := range seen {
		names = append(names, n)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString("# Code generated by schema/python/gen — DO NOT EDIT.\n")
	b.WriteString("#\n")
	b.WriteString("# Source: canonical Go governed types in internal/schema, internal/governor,\n")
	b.WriteString("# internal/connectors. Regenerate with `make generate-python`.\n")
	b.WriteString("#\n")
	b.WriteString("# Stdlib-only: dataclasses + enum, no third-party dependencies. Enum values are\n")
	b.WriteString("# read from Go source and struct shapes from Go reflection, so this module never\n")
	b.WriteString("# drifts from the kernel (Language-Layer Contract §7: generated, not hand-written).\n")
	b.WriteString(`"""Governed type contracts for NAVI (Go → Python). Stdlib-only."""` + "\n")
	b.WriteString("from __future__ import annotations\n\n")
	b.WriteString("from dataclasses import dataclass, field\n")
	b.WriteString("from enum import Enum, IntEnum\n")
	b.WriteString("from typing import Any, Dict, List, Optional\n\n")

	b.WriteString("__all__ = [\n")
	for _, n := range names {
		b.WriteString("    " + strconv.Quote(n) + ",\n")
	}
	b.WriteString("]\n")

	// Enums.
	for _, e := range m.Enums {
		b.WriteString("\n\n")
		base := "str, Enum"
		if !e.IsString {
			base = "IntEnum"
		}
		fmt.Fprintf(&b, "class %s(%s):\n", e.Name, base)
		if len(e.Members) == 0 {
			b.WriteString("    pass\n")
			continue
		}
		for _, mem := range e.Members {
			if e.IsString {
				fmt.Fprintf(&b, "    %s = %s\n", mem.Name, strconv.Quote(mem.StrVal))
			} else {
				fmt.Fprintf(&b, "    %s = %d\n", mem.Name, mem.IntVal)
			}
		}
	}

	// Dataclasses.
	for _, s := range m.Structs {
		b.WriteString("\n\n@dataclass\n")
		fmt.Fprintf(&b, "class %s:\n", s.Name)
		fmt.Fprintf(&b, "    %q\n", "Generated from Go "+s.GoRef+".")
		if len(s.Fields) == 0 {
			b.WriteString("    pass\n")
			continue
		}
		for _, f := range s.Fields {
			ann, def := pyType(m, f.Type)
			fmt.Fprintf(&b, "    %s: %s %s\n", f.JSONName, ann, def)
		}
	}

	return b.String(), nil
}
