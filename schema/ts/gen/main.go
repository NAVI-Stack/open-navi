// Command gen emits TypeScript types + Zod schemas for NAVI's governed types,
// sourced from the canonical Go definitions in internal/schema, internal/governor,
// and internal/connectors.
//
// It is the TypeScript half of the single governed-type codegen flow. The shared
// input set and type discovery live in schema/codegen, which the Python emitter
// (schema/python/gen) renders from too — so both languages emit the same governed
// contracts from the same Go types and can never drift (Language-Layer Contract §7:
// generated, not hand-written). This command renders the TypeScript projection:
// one Zod schema per governed type plus a `z.infer` type alias, consumed by the
// browser Console at web-src/navi-console/src/types/generated/.
//
// Output is wired into `make generate-ts`. The emitted module replaces the
// hand-written governed Zod in web-src/navi-console/src/types/api; UI-only state
// stays hand-written there.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"strconv"
	"strings"

	"github.com/ceoai/navi/schema/codegen"
)

func main() {
	root := flag.String("root", ".", "module root directory")
	out := flag.String("out", filepath.Join("web-src", "navi-console", "src", "types", "generated", "governed.ts"), "output .ts path")
	flag.Parse()

	model, err := codegen.Build(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}

	src, err := emit(model)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}

	outPath := *out
	if !filepath.IsAbs(outPath) {
		outPath = filepath.Join(*root, outPath)
	}
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(outPath, []byte(src), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	fmt.Println("gen: wrote", outPath)
}

// zodType maps a Go type to a Zod schema expression, resolving enum/struct
// references through the model. It is a pure projection — discovery already
// happened in codegen.Build. Pointer-ness (optionality) is handled by the caller
// at field level, so this never emits a trailing `.optional()`.
func zodType(m *codegen.Model, t reflect.Type) string {
	if t.Kind() == reflect.Pointer {
		return zodType(m, t.Elem())
	}
	if e, ok := m.Enum(t); ok {
		return e.Name + "Schema"
	}
	switch t.Kind() {
	case reflect.String:
		return "z.string()"
	case reflect.Bool:
		return "z.boolean()"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "z.number()"
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 { // []byte / json.RawMessage
			return "z.unknown()"
		}
		return "z.array(" + zodType(m, t.Elem()) + ")"
	case reflect.Map:
		return "z.record(" + zodType(m, t.Key()) + ", " + zodType(m, t.Elem()) + ")"
	case reflect.Struct:
		if t.PkgPath() == "time" && t.Name() == "Time" {
			return "z.string()" // RFC3339 timestamp
		}
		if codegen.IsKernelPkg(t.PkgPath()) && t.Name() != "" {
			return t.Name() + "Schema"
		}
		return "z.unknown()"
	case reflect.Interface:
		return "z.unknown()"
	default:
		return "z.unknown()"
	}
}

// emit renders the full TypeScript module from the contract model.
func emit(m *codegen.Model) (string, error) {
	var b strings.Builder
	b.WriteString("// Code generated by schema/ts/gen — DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Source: canonical Go governed types in internal/schema, internal/governor,\n")
	b.WriteString("// internal/connectors. Regenerate with `make generate-ts`.\n")
	b.WriteString("//\n")
	b.WriteString("// Governed types + Zod schemas (Language-Layer Contract §7: generated, not\n")
	b.WriteString("// hand-written). Enum values are read from Go source and struct shapes from Go\n")
	b.WriteString("// reflection, so this module never drifts from the kernel. UI-only state stays\n")
	b.WriteString("// hand-written in src/types/api.ts.\n")
	b.WriteString("import { z } from 'zod';\n")

	// Enums first — structs reference their schemas by name.
	for _, e := range m.Enums {
		b.WriteString("\n")
		if e.IsString {
			b.WriteString("export const " + e.Name + "Schema = z.enum([\n")
			for _, mem := range e.Members {
				b.WriteString("  " + strconv.Quote(mem.StrVal) + ",\n")
			}
			b.WriteString("]);\n")
		} else {
			b.WriteString("export const " + e.Name + "Schema = z.union([\n")
			for _, mem := range e.Members {
				fmt.Fprintf(&b, "  z.literal(%d),\n", mem.IntVal)
			}
			b.WriteString("]);\n")
		}
		b.WriteString("export type " + e.Name + " = z.infer<typeof " + e.Name + "Schema>;\n")
	}

	// Structs, ordered so every referenced schema is declared before use — Zod
	// consts must be initialized before they are referenced, unlike Python's
	// forward-referencing class bodies.
	for _, s := range codegen.OrderByReferences(m.Structs) {
		b.WriteString("\n/** Generated from Go " + s.GoRef + ". */\n")
		b.WriteString("export const " + s.Name + "Schema = z.object({\n")
		for _, f := range s.Fields {
			expr := zodType(m, f.Type)
			// A pointer field or an omitempty field may be absent from the payload.
			if f.Type.Kind() == reflect.Pointer || f.OmitEmpty {
				expr += ".optional()"
			}
			b.WriteString("  " + tsKey(f.JSONName) + ": " + expr + ",\n")
		}
		b.WriteString("});\n")
		b.WriteString("export type " + s.Name + " = z.infer<typeof " + s.Name + "Schema>;\n")
	}

	return b.String(), nil
}

// tsKey renders an object key, quoting it only when it is not a valid bare
// JS identifier (governed JSON keys are snake_case or PascalCase, so this is
// belt-and-suspenders).
func tsKey(name string) string {
	if isIdent(name) {
		return name
	}
	return strconv.Quote(name)
}

func isIdent(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		ok := r == '_' || r == '$' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z')
		if i > 0 {
			ok = ok || (r >= '0' && r <= '9')
		}
		if !ok {
			return false
		}
	}
	return true
}
