// GetSummaryTable is a helper for Task 5/Task 6 compatibility if needed,
// though RunReviewScreen now handles the display.
func GetSummaryTable(ownerName, provider, model, connector string, params map[string]string) string {
	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("Owner: %s\n", ownerName))
	sb.WriteString(fmt.Sprintf("Provider: %s\n", provider))
	sb.WriteString(fmt.Sprintf("Model: %s\n", model))
	sb.WriteString(fmt.Sprintf("Connector: %s\n", connector))
	for k, v := range params {
		sb.WriteString(fmt.Sprintf("  %s: %s\n", k, MaskSecret(v)))
	}
	return sb.String()
}
